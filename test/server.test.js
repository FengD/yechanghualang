import assert from 'node:assert/strict';
import test from 'node:test';
import {mkdtemp, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {artwork} from '../public/catalog.js';
import {DEFAULT_SETTINGS} from '../src/game.js';
import {startServer} from '../src/server.js';
import {peer} from './peer.js';

test('single room, host authority, 10-person capacity, private data, reconnection and restart', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'night-gallery-test-'));
  const rules = {...DEFAULT_SETTINGS, seats: 3, format: 'sealed', rounds: 2};
  const key = 'private-create-key';
  let server = await startServer({port: 0, host: '127.0.0.1', directory, createKey: key});
  const all = [];
  const base = () => `http://127.0.0.1:${server.port}`;
  const ws = () => `ws://127.0.0.1:${server.port}/live`;
  const enter = async first => {
    const client = await peer(ws(), first);
    all.push(client);
    return client;
  };
  t.after(async () => {
    for (const client of all) client.close();
    await server.close();
    await rm(directory, {recursive: true});
  });
  assert.deepEqual(await (await fetch(base() + '/status')).json(), {exists: false, createKey: true});
  const home = await fetch(base(), {headers: {'Accept-Encoding': 'br'}});
  assert.equal(home.headers.get('content-encoding'), 'br');
  assert.match(await home.text(), /夜场画廊/);
  assert.equal((await fetch(base(), {headers: {'Accept-Encoding': 'br', 'If-None-Match': home.headers.get('etag')}})).status, 304);
  const thumbnail = await fetch(base() + '/art/v1-0-s.webp');
  assert.match(thumbnail.headers.get('cache-control'), /immutable/);
  assert.ok((await thumbnail.arrayBuffer()).byteLength < 10000);
  const setup = {type: 'create', name: '房主', title: '周末', rules, key};
  const unauthorized = await enter({...setup, key: 'wrong'});
  assert.match(unauthorized.packets[0].message, /密钥/);
  unauthorized.close();
  const claim = 'z'.repeat(32);
  const host = await enter({...setup, claim});
  assert.equal(host.token, claim);
  const recovered = await enter({...setup, claim});
  assert.equal(recovered.snapshot.self.id, host.snapshot.self.id);
  const invite = recovered.snapshot.self.invite;
  const guests = await Promise.all(Array.from({length: 9}, (_, i) =>
    enter({type: 'join', invite, name: '访客' + i, role: i < 2 ? 'play' : 'watch'})));
  const extra = await enter({type: 'join', invite, name: '访客9', role: 'watch'});
  assert.match(extra.packets[0].message, /10 人上限/);
  assert.equal(guests[0].snapshot.self.invite, null);
  assert.match((await guests[0].command({type: 'settings', rules})).message, /房主/);
  assert.match((await guests[0].command({type: 'start'})).message, /房主/);
  assert.equal((await recovered.command({type: 'start'})).type, 'ok');
  const members = [recovered, guests[0], guests[1]];
  const watcher = guests[2];
  await Promise.all([...members, watcher].map(member => member.until(() => member.snapshot.table?.phase === 'nominate')));
  assert.deepEqual(watcher.snapshot.me, null);
  assert.equal(watcher.snapshot.people.length, 10);
  assert.ok(watcher.snapshot.people.every(person => !Object.hasOwn(person, 'token')));
  const {lot, phase, seller} = recovered.snapshot.table;
  const epoch = recovered.snapshot.room.epoch;
  const curator = members.find(p => p.snapshot.self.id === seller);
  const [buyer, other] = members.filter(p => p !== curator);
  const card = curator.snapshot.me.hand[0];
  assert.match((await watcher.command({type: 'nominate', epoch, lot, phase, card})).message, /只有参赛者/);
  assert.match((await curator.command({type: 'nominate', epoch: 'expired', lot, phase, card})).message, /另一局/);
  assert.equal((await curator.command({type: 'nominate', epoch, lot, phase, card})).type, 'ok');
  await watcher.until(() => watcher.snapshot.table.phase === 'sealed');
  const amount = artwork(card).reserve + 12;
  assert.equal((await buyer.command({type: 'bid', epoch, lot, phase: 'sealed', amount})).type, 'ok');
  await watcher.until(() => watcher.snapshot.table.responses === 1);
  assert.ok(!Object.hasOwn(watcher.snapshot.table, 'offers'));
  assert.equal(watcher.snapshot.table.high, null);
  const sameSeat = await enter({type: 'resume', token: buyer.token});
  assert.equal(sameSeat.snapshot.me.offer, amount);
  assert.equal(sameSeat.snapshot.self.id, buyer.snapshot.self.id);
  const owner = buyer === recovered ? sameSeat : recovered;
  const pause = {type: 'pause', epoch, lot, phase: 'sealed', clock: 0};
  assert.match((await watcher.command(pause)).message, /只有房主/);
  assert.equal((await owner.command(pause)).type, 'ok');
  await watcher.until(() => watcher.snapshot.table.pausedMs != null);
  const frozen = watcher.snapshot.table.pausedMs;
  assert.ok(frozen > 0);
  const pass = {type: 'pass', epoch, lot, phase: 'sealed'};
  assert.match((await other.command({...pass, clock: 1})).message, /暂停/);
  await server.close();
  server = await startServer({port: 0, host: '127.0.0.1', directory, createKey: key});
  const again = await enter({type: 'resume', token: recovered.token});
  assert.equal(again.snapshot.sales.length, 0);
  assert.equal(again.snapshot.table.lot, 1);
  assert.equal(again.snapshot.table.pausedMs, frozen);
  assert.equal(again.snapshot.people.length, 10);
  const returnedBuyer = buyer === recovered ? again : await enter({type: 'resume', token: buyer.token});
  const returnedOther = other === recovered ? again : await enter({type: 'resume', token: other.token});
  assert.equal(returnedBuyer.snapshot.me.offer, amount);
  assert.equal((await again.command({type: 'sync'})).type, 'ok');
  assert.equal(again.packets.filter(p => p.type === 'snapshot').length, 2);
  assert.equal((await again.command({...pause, type: 'continue', clock: 1})).type, 'ok');
  await again.until(() => again.snapshot.table.pausedMs === null);
  assert.match((await returnedOther.command(pass)).message, /阶段已切换/);
  assert.equal((await returnedOther.command({...pass, clock: 2})).type, 'ok');
  await again.until(() => again.snapshot.sales.length === 1);
  assert.equal(again.snapshot.sales[0].price, artwork(card).reserve);
  assert.equal(again.snapshot.sales[0].buyer, returnedBuyer.snapshot.self.id);
  assert.equal(again.snapshot.table.lot, 2);
  assert.equal((await again.command({type: 'reset', epoch})).type, 'ok');
  await again.until(() => again.snapshot.table === null);
  assert.equal((await again.command({type: 'kick', person: watcher.snapshot.self.id})).type, 'ok');
  const later = await enter({type: 'join', invite, role: 'watch', name: '后来的观众'});
  assert.ok(later.token);
});
